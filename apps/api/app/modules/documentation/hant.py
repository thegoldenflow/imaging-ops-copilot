def to_hant(text: str) -> str:
    """Traditional Chinese for a Simplified string (phrase overrides, then the character table)."""
    if not text:
        return text
    out, i = [], 0
    longest = max(map(len, PHRASES))
    while i < len(text):
        for n in range(min(longest, len(text) - i), 1, -1):
            chunk = text[i:i + n]
            if chunk in PHRASES:
                out.append(PHRASES[chunk])
                i += n
                break
        else:
            out.append(S2T.get(text[i], text[i]))
            i += 1
    return "".join(out)
