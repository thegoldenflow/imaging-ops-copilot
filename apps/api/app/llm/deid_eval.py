"""Free-text de-identification eval (spec 6.3): scores app/llm/freetext_deid.py on
evals/deid/cases.jsonl (generated by scripts/gen_deid_eval.py).

For every note the de-identifier gets the identifiers the record would give it
(the patient's names, MRN, health card, phone, address; the staff roster), then

- the rule layer alone, and
- the rule layer plus the second pass through the LLM gateway (the configured
  provider; the mock provider's heuristic detector without a key)

are scored against the gold spans:

- recall: a gold PHI span counts as caught only when every non-space character
  of it is inside a redacted span (a half-redacted phone number is a leak);
- precision: a redacted span is correct when it overlaps a gold span;
- date offsets: of the caught dates with a known day, how many tokens carry the
  right number of days from the reference date.

Thresholds: recall >= 0.98 and precision >= 0.90 for the full pipeline (6.3: no
merge below them). The metrics show the pipeline works on synthetic notes; they
are not a measure of performance on real clinical text.
"""

from __future__ import annotations

import json
import time
from dataclasses import dataclass, field
from datetime import date, datetime
from pathlib import Path

from app.llm.freetext_deid import FreeTextDeidentifier, Span, deidentify
from app.modules.evals.paths import EVALS_DIR

CASES = EVALS_DIR / "deid" / "cases.jsonl"
REPORT_DIR = EVALS_DIR / "deid"
RECALL_MIN = 0.98
PRECISION_MIN = 0.90


def load_cases(path: Path = CASES) -> list[dict]:
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def deidentifier_for(case: dict) -> FreeTextDeidentifier:
    deid = FreeTextDeidentifier(reference=date.fromisoformat(case["reference_date"]))
    known = case["known"]
    patient = known["patient"]
    deid.add_person(patient["names"], "PERSON")
    deid.add_known(patient.get("mrn"), "MRN")
    deid.add_known(patient.get("health_card"), "HEALTH_CARD")
    deid.add_known(patient.get("phone"), "PHONE")
    deid.add_known(patient.get("address"), "ADDRESS")
    deid.add_known(patient.get("postal_code"), "ADDRESS")
    for name in known.get("staff") or []:
        deid.add_person([name], "STAFF")
    return deid


def _full_spans(text: str, deid: FreeTextDeidentifier, second_pass: bool) -> tuple[list[Span], str, str]:
    """Rule spans plus the second pass's spans, all in the coordinates of the original text."""
    rule = deid.detect(text)
    if not second_pass:
        return rule, deid.apply(text, rule), "skipped"
    result = deidentify(text, deid, second_pass=True, record_misses=False)
    if not result.misses:
        return rule, result.text, result.second_pass
    # Map the second pass's spans (found in the redacted text) back to the original text.
    segments: list[tuple[int, int, int]] = []  # (redacted start, redacted end, original start)
    red_pos = orig_pos = 0
    for s in sorted(rule, key=lambda s: s.start):
        length = s.start - orig_pos
        segments.append((red_pos, red_pos + length, orig_pos))
        red_pos += length + len(deid.token_for(s, text[s.start:s.end]))
        orig_pos = s.end
    segments.append((red_pos, red_pos + len(text) - orig_pos, orig_pos))
    extra = []
    for m in result.misses:
        seg = next((g for g in segments if g[0] <= m.start and m.end <= g[1]), None)
        if seg is not None:
            offset = seg[2] - seg[0]
            extra.append(Span(m.start + offset, m.end + offset, m.kind, "model", m.date_offset))
    return rule + extra, result.text, result.second_pass


@dataclass
class Score:
    gold: int = 0
    caught: int = 0
    predicted: int = 0
    correct: int = 0
    dates_with_day: int = 0
    dates_offset_right: int = 0
    by_kind: dict = field(default_factory=dict)
    known_gold: int = 0
    known_caught: int = 0
    leaks: list = field(default_factory=list)
    false_positives: list = field(default_factory=list)

    @property
    def recall(self) -> float:
        return self.caught / self.gold if self.gold else 1.0

    @property
    def precision(self) -> float:
        return self.correct / self.predicted if self.predicted else 1.0

    def summary(self) -> dict:
        return {
            "recall": round(self.recall, 4), "precision": round(self.precision, 4), "gold_spans": self.gold,
            "caught": self.caught, "redacted_spans": self.predicted, "correct_redactions": self.correct,
            "recall_known_identifiers": round(self.known_caught / self.known_gold, 4) if self.known_gold else None,
            "recall_pattern_only": round((self.caught - self.known_caught) / (self.gold - self.known_gold), 4)
            if self.gold > self.known_gold else None,
            "date_offset_accuracy": round(self.dates_offset_right / self.dates_with_day, 4)
            if self.dates_with_day else None,
            "by_kind": {k: {"gold": v[0], "caught": v[1], "recall": round(v[1] / v[0], 4) if v[0] else None}
                        for k, v in sorted(self.by_kind.items())},
        }


def _covered(gold: dict, spans: list[Span], text: str) -> bool:
    chars = [i for i in range(gold["start"], gold["end"]) if not text[i].isspace()]
    return all(any(s.start <= i < s.end for s in spans) for i in chars)


def score_case(case: dict, spans: list[Span], score: Score) -> None:
    text = case["text"]
    for g in case["phi"]:
        caught = _covered(g, spans, text)
        score.gold += 1
        score.caught += caught
        kind = score.by_kind.setdefault(g["kind"], [0, 0])
        kind[0] += 1
        kind[1] += caught
        if g.get("known"):
            score.known_gold += 1
            score.known_caught += caught
        if not caught:
            score.leaks.append({"case": case["id"], "kind": g["kind"], "text": g["text"]})
        if g["kind"] == "DATE" and "days" in g and caught:
            score.dates_with_day += 1
            covering = next((s for s in spans if s.start <= g["start"] and g["end"] <= s.end and s.kind == "DATE"), None)
            score.dates_offset_right += bool(covering and covering.date_offset == g["days"])
    for s in spans:
        score.predicted += 1
        hit = any(s.start < g["end"] and g["start"] < s.end for g in case["phi"])
        score.correct += hit
        if not hit:
            score.false_positives.append({"case": case["id"], "kind": s.kind, "source": s.source,
                                          "text": text[s.start:s.end]})


def evaluate(cases: list[dict] | None = None, *, second_pass: bool = True) -> dict:
    from app.llm.gateway import get_gateway

    cases = cases if cases is not None else load_cases()
    started = time.monotonic()
    rule, full = Score(), Score()
    statuses: dict[str, int] = {}
    for case in cases:
        deid = deidentifier_for(case)
        rule_spans = deid.detect(case["text"])
        score_case(case, rule_spans, rule)
        spans, _, status = _full_spans(case["text"], deidentifier_for(case), second_pass)
        statuses[status] = statuses.get(status, 0) + 1
        score_case(case, spans, full)
    passed = full.recall >= RECALL_MIN and full.precision >= PRECISION_MIN
    return {
        "eval": "deid_freetext", "spec": "6.3", "run_at": datetime.now().isoformat(timespec="seconds"),
        "cases": len(cases), "gold_spans": rule.gold,
        "thresholds": {"recall": RECALL_MIN, "precision": PRECISION_MIN}, "passed": passed,
        "second_pass": {"enabled": second_pass, "provider": get_gateway().mode, "outcomes": statuses},
        "rule_layer": rule.summary(), "pipeline": full.summary(),
        "pipeline_leaks": full.leaks[:50], "pipeline_false_positives": full.false_positives[:50],
        "rule_layer_leaks": rule.leaks[:50],
        "seconds": round(time.monotonic() - started, 1),
        "note": "Synthetic notes generated alongside the rules (scripts/gen_deid_eval.py); the metrics show the "
                "pipeline works, not performance on real clinical text. With the mock provider the second pass is "
                "a heuristic stand-in, not a model.",
    }


def markdown(report: dict) -> str:
    p, r = report["pipeline"], report["rule_layer"]
    lines = [
        "# Free-text de-identification eval (spec 6.3)", "",
        f"Run {report['run_at']} on {report['cases']} synthetic notes with {report['gold_spans']} planted PHI spans "
        f"(`evals/deid/cases.jsonl`). Second pass: {report['second_pass']['provider']} provider "
        f"({', '.join(f'{k} {v}' for k, v in report['second_pass']['outcomes'].items())}).", "",
        f"**{'PASSED' if report['passed'] else 'FAILED'}**: thresholds recall >= {report['thresholds']['recall']}, "
        f"precision >= {report['thresholds']['precision']} (rule layer + second pass).", "",
        "| | Recall | Precision | Caught / gold | Correct / redacted | Known identifiers | Pattern only | Date offsets |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for label, s in (("Rule layer", r), ("Rule layer + second pass", p)):
        lines.append(f"| {label} | {s['recall']:.4f} | {s['precision']:.4f} | {s['caught']} / {s['gold_spans']} | "
                     f"{s['correct_redactions']} / {s['redacted_spans']} | {s['recall_known_identifiers']} | "
                     f"{s['recall_pattern_only']} | {s['date_offset_accuracy']} |")
    lines += ["", "Recall by kind (pipeline):", "", "| Kind | Gold | Caught | Recall |", "| --- | --- | --- | --- |"]
    for kind, v in p["by_kind"].items():
        lines.append(f"| {kind} | {v['gold']} | {v['caught']} | {v['recall']} |")
    lines += ["", f"Leaks (pipeline, first {min(50, len(report['pipeline_leaks']))}):", ""]
    lines += [f"- {x['case']} {x['kind']}: `{x['text']}`" for x in report["pipeline_leaks"]] or ["- none"]
    lines += ["", f"Redactions without PHI (pipeline, first {min(50, len(report['pipeline_false_positives']))}):", ""]
    lines += [f"- {x['case']} {x['kind']} ({x['source']}): `{x['text']}`"
              for x in report["pipeline_false_positives"]] or ["- none"]
    lines += ["", f"_{report['note']}_", ""]
    return "\n".join(lines)


def write_report(report: dict, directory: Path = REPORT_DIR) -> tuple[Path, Path]:
    directory.mkdir(parents=True, exist_ok=True)
    json_path, md_path = directory / "report.json", directory / "report.md"
    json_path.write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    md_path.write_text(markdown(report), encoding="utf-8")
    return json_path, md_path
