"""Write docs/safety-tiers.md (spec 8.3, 8.1, 6.7) from the same views as the Safety tiers and Roadmap pages.

    cd apps/api && uv run python scripts/safety_doc.py           # rewrite docs/safety-tiers.md
    cd apps/api && uv run python scripts/safety_doc.py --check   # exit 1 when the file is out of date

The words come from config/safety.yaml and config/roadmap.yaml, the agents, tools and sign-off roles from the
registries (app/modules/roadmap/service.py). Eval numbers are left out on purpose (they change with every run and
live in evals/README.md), so the file changes only when the YAML or the registries change; tests/test_roadmap.py
fails when it is out of date. No database is needed.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.core.models import Role  # noqa: E402
from app.modules.roadmap import service  # noqa: E402

REPO = Path(__file__).resolve().parents[3]
OUT = REPO / "docs" / "safety-tiers.md"
KIND = {"runtime_agent": "runtime agent", "embedded_agent": "embedded agent", "module": "module (no model)"}
ROLE = {r.value: r.value.replace("_", " ") for r in Role}


def cell(text: object) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def roles(values: list[str]) -> str:
    return ", ".join(ROLE.get(v, v) for v in values) or "none"


def render() -> str:
    view = service.safety_view()
    cards = service.cards_view()
    p = view["platform"]
    k, lv = p["by_kind"], p["by_level"]
    out: list[str] = [
        "# Safety tiers, guardrails and roadmap",
        "",
        "Generated by `apps/api/scripts/safety_doc.py` from `apps/api/config/safety.yaml`, `apps/api/config/roadmap.yaml` "
        "and the agent and tool registries (`apps/api/config/agents/`, `apps/api/config/tools/`). Do not edit it by hand: "
        "change the YAML or the registry, then run `cd apps/api && uv run python scripts/safety_doc.py` "
        "(`tests/test_roadmap.py` fails while this file is out of date). In the app the same content is on the "
        "**Safety tiers** (`/safety`) and **Roadmap** (`/roadmap`) pages, with the latest eval results next to each "
        "guardrail. Eval numbers: [evals/README.md](../evals/README.md). Talk tracks: "
        "[interview-narrative.md](interview-narrative.md).",
        "",
    ]
    out += [f"> {s}" for s in view["positioning"]]
    out += [
        "",
        f"Registered today: {p['entries']} agents and modules ({k['runtime_agent']} runtime agents, "
        f"{k['embedded_agent']} embedded agents, {k['module']} modules without a model) and {p['tools']} tools "
        f"({lv['read']} read, {lv['recommend']} recommend, {lv['action']} action, {lv['privileged']} privileged).",
        "",
        "## Three risk tiers (spec 8.3)",
        "",
        "Every registry entry declares one tier; the tier decides what the AI may do, who signs and how it is "
        "explained to a regulator. The sign-off roles are the union of the registry entries' `required_signoff_role`.",
        "",
        "| Tier | Definition | Examples (spec) | AI may | Signs or approves: spec; registry | Regulation and validation |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for t in view["tiers"]:
        may = ", ".join(t["allowed_ai_actions"]) + ("; never " + ", ".join(t["never"]) if t["never"] else "")
        out.append(f"| `{t['id']}` {cell(t['name'])} | {cell(t['definition'])} | {cell(t['spec_examples'])} | "
                   f"{cell(may)} | {cell(t['spec_signoff'])}; registry: {cell(roles(t['signoff_roles']))} | "
                   f"{cell(t['regulatory'])} |")
    for t in view["tiers"]:
        c = t["counts"]
        out += ["", f"### `{t['id']}`: {len(t['entries'])} registry entries "
                    f"({c['runtime_agent']} runtime agents, {c['embedded_agent']} embedded agents, {c['module']} modules)",
                "", "| Entry | Kind | Purpose | Signer |", "| --- | --- | --- | --- |"]
        for e in t["entries"]:
            signer = roles(e["required_signoff_role"]) + (" (all co-sign)" if e["cosign"] else "")
            out.append(f"| `{e['agent_id']}` {e['version']} | {KIND[e['kind']]} | {cell(e['purpose'])} | {cell(signer)} |")
    out += [
        "",
        "## Second axis: tools by side effect (spec 6.4)",
        "",
        "Modules are tiered by risk, tools by side effect, and the axes are independent: an `ops` module can call a "
        "privileged tool (a bed move, an OR booking), and that call still needs a recorded human approval.",
        "",
        "| Level | Meaning | Runs only when | Registered tools |",
        "| --- | --- | --- | --- |",
    ]
    for level in view["side_effect_levels"]:
        names = ", ".join(f"`{t['tool_id']}`" for t in level["tools"])
        out.append(f"| `{level['id']}` | {cell(level['meaning'])} | {cell(level['precondition'])} | "
                   f"{len(level['tools'])}: {names} |")
    levels = [lv_["id"] for lv_ in view["side_effect_levels"]]
    out += ["", "Registry entries per tier that hold at least one tool of each level:", "",
            "| Tier | " + " | ".join(levels) + " |", "| --- |" + " --- |" * len(levels)]
    for t in view["tiers"]:
        out.append(f"| `{t['id']}` | " + " | ".join(str(len(t["reach"][x])) for x in levels) + " |")
    out += ["", "## The retired Level 0–4 scale (spec 8.3)", "",
            "The platform supplement's Level 0–4 risk scale is no longer used; it maps onto the two axes like this:", "",
            "| Level | Module tier | Tool level | Note |", "| --- | --- | --- | --- |"]
    for m in view["level_mapping"]:
        out.append(f"| {m['level']} | {', '.join(m['tiers'])} | {', '.join(m['tools'])} | {cell(m['note'] or '')} |")
    out += ["", "## Guardrails", "", "| Guardrail | Rule | Spec | Where it is enforced | Evidence |",
            "| --- | --- | --- | --- | --- |"]
    for g in view["guardrails"]:
        code = "<br>".join(f"`{c}`" for c in g["code"])
        out.append(f"| {cell(g['title'])} | {cell(g['rule'])} | {g['spec']} | {code} | {cell(g['evidence'])} |")
    out += ["", "## Honest boundaries (said unprompted when asked)", ""]
    out += [f"- {b['text']}" for b in view["honest_boundaries"]]
    out += ["", "## Definition of done", "", view["definition_of_done"], "",
            "## Roadmap (spec 8.1)", "",
            f"{cards['counts']['cards']} modules the platform could grow; none is implemented. "
            f"{cards['counts']['preset']} are walked through once in the hospital storyline on preset data. Every card "
            f"ends with: *{cards['footer']}*", "",
            "| Module | Pain | Data source | Risk tier | Reuses | In the demo |", "| --- | --- | --- | --- | --- | --- |"]
    for c in cards["cards"]:
        demo = c["demo_note"]
        if c["step"]:
            demo += f" Storyline step {c['step']['n']} ({c['step']['title']})."
        if c["registry_entry"]:
            demo += f" Registry: `{c['registry_entry']['path']}`."
        out.append(f"| {cell(c['title'])} | {cell(c['pain'])} | {cell(c['data_source'])} | `{c['risk_tier']}` | "
                   f"{cell(c['reuses'])} | {cell(demo)} |")
    return "\n".join(out) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when docs/safety-tiers.md is out of date")
    args = parser.parse_args()
    problems = service.check(REPO)
    if problems:
        print("\n".join(problems))
        sys.exit(1)
    text = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(REPO)} is out of date: run `uv run python scripts/safety_doc.py`")
            sys.exit(1)
        print(f"{OUT.relative_to(REPO)} is current")
        return
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    from _stdio import utf8_stdio

    utf8_stdio()
    main()
